def _load_analyst_blacklist() -> set[str]:
    """Return set of timeframes the analyst has flagged as dead/noisy.

    Falls through silently if the report doesn't exist yet (first runs).
    """
    try:
        data = json.loads(ANALYST_REPORT_PATH.read_text())
        findings = data.get("findings", {}) or {}
        return set(findings.get("dead_timeframes", [])) | set(findings.get("noisy_timeframes", []))
    except Exception:
        return set()


def _has_data_coverage(timeframe: str) -> bool:
    """Skip the timeframe if BTC's feather doesn't cover the backtest cutoff."""
    btc_file = DATA_DIR / f"BTC_USDT_USDT-{timeframe}-futures.feather"
    if not btc_file.exists():
        return False
    try:
        import pandas as pd
        df = pd.read_feather(btc_file)
        date_col = "date" if "date" in df.columns else df.columns[0]
        return str(df[date_col].max()) >= DATA_COVERAGE_CUTOFF
    except Exception:
        return False


def _available_timeframes(candidates: list[str]) -> list[str]:
    """Filter candidates by analyst blacklist + data coverage."""
    blacklist = _load_analyst_blacklist()
    return [tf for tf in candidates if tf not in blacklist and _has_data_coverage(tf)]


