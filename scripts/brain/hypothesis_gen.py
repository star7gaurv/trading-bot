# Valid threshold scale for the z-score era (_GLOBAL_STD=0.30, fixed 2026-06-08).
# Configs outside these bounds are from the retired raw-%/0.95-std scale and must
# neither be queued nor used as parents for guided/bayes exploration.
LT_BOUNDS = (0.1, 0.8)
ST_BOUNDS = (-1.0, -0.1)


def _in_current_scale(config: dict) -> bool:
    """True if a config's thresholds fall inside the current valid z-score scale."""
    lt = config.get("long_threshold")
    st = config.get("short_threshold")
    if lt is not None and not (LT_BOUNDS[0] <= lt <= LT_BOUNDS[1]):
        return False
    if st is not None and not (ST_BOUNDS[0] <= st <= ST_BOUNDS[1]):
        return False
    return True


def _clamp(v: dict, param: str) -> dict:
    """Clamp a perturbed param to a sane range."""
    if "threshold" == param.split("_")[-1] and param != "ml_threshold":
        if param == "short_threshold":
            # FIXED 2026-06-08: _GLOBAL_STD=0.30; max useful ST=-1.0 (effective -0.65σ in mature model)
            v[param] = max(ST_BOUNDS[0], min(ST_BOUNDS[1], v[param]))
        else:
            # FIXED 2026-06-08: max useful LT=0.8 (effective 0.52 in immature, 1.04 in mature model)
            v[param] = max(LT_BOUNDS[0], min(LT_BOUNDS[1], v[param]))
    elif param == "ml_threshold":
        v[param] = max(0.45, min(0.85, v[param]))
    elif param.startswith("k_"):
        v[param] = max(0.5, min(4.0, v[param]))
    elif param == "stability_n":
        # Bug 4 fix (2026-05-30): clamp to [1, 4]. stability_n=-1 was being
        # queued (perturbation -1 from base=1), which the strategy silently
        # corrects to 1 via max(1,n) — but the config_hash stores -1, causing
        # confusion in logs and any future promotion. Min=1 is the valid floor.
        v[param] = max(1, min(4, int(v[param])))
    return v


def generate_safe_band(seed: dict | None = None, n: int = 8) -> list[dict]:
    """Small perturbations around the current best config — for the SAME architecture."""
    base = dict(seed or _current_best_config() or SEED_CONFIG_V23)
    # Older log entries don't have 'arch' — infer from strategy name
    if "arch" not in base:
        base["arch"] = "v22" if base.get("strategy") == "FinBuddyFreqAI" else "v23"

    # FIXED 2026-06-08: With _GLOBAL_STD=0.30, max useful LT=0.8. Any config with LT>0.8
    # will produce near-zero longs (effective threshold > 1.04 in mature model).
    # Override to seed LT (0.5) when anchoring on stale high-LT configs.
    if base.get("arch", "v23") == "v23" and base.get("long_threshold", 0.3) > 0.8:
        base = dict(base)
        base["long_threshold"] = SEED_CONFIG_V23["long_threshold"]  # 0.5

    perturbations = PERTURB_V22 if base["arch"] == "v22" else PERTURB_V23

    random.shuffle(perturbations)
    out = []
    for (param, delta, rationale) in perturbations[:n]:
        v = dict(base)
        if param not in v:
            continue
        if isinstance(v[param], int):
            v[param] = max(1, int(v[param] + delta))
        else:
            v[param] = round(float(v[param]) + float(delta), 3)
            v = _clamp(v, param)
        if v == base:
            continue
        out.append({
            "band": "safe",
            "rationale": f"safe [{base['arch']}]: {param} {'+' if delta>=0 else ''}{delta} ({rationale})",
            "config": v,
        })
    return out


def generate_safe_band_both(n_per_arch: int = 4) -> list[dict]:
    """SAFE band for active architectures (v22 skipped when V22_ENABLED=False).

    Seed each architecture from its own current-best. Disabled arches are
    silently skipped — same pattern as N8N pipeline retirement: code stays,
    flag flips off.
    """
    arch_seeds = [SEED_CONFIG_V23]
    if V22_ENABLED:
        arch_seeds.insert(0, SEED_CONFIG_V22)
    out = []
    for arch_seed in arch_seeds:
        best = _current_best_config_for_arch(arch_seed["arch"]) or arch_seed
        out += generate_safe_band(seed=best, n=n_per_arch)
    return out


