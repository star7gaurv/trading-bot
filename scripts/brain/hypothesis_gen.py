def queue_seed_if_empty() -> int:
    """If queue and log are both empty, queue seed configs for enabled arches only."""
    from experiment_log import read_log, read_queue
    if read_log() or read_queue():
        return 0
    seeds = [SEED_CONFIG_V23]
    if V22_ENABLED:
        seeds.append(SEED_CONFIG_V22)
    queued = 0
    for seed in seeds:
        cfg = _stamp_target_version(seed)
        for win_name, timerange in WINDOWS.items():
            queue_hypothesis(
                config=cfg,
                band="seed",
                rationale=f"seed [{seed['arch']}]: baseline",
                window=win_name,
                timerange=timerange,
            )
            queued += 1
    return queued


def queue_v22_seeds() -> int:
    """One-shot helper to seed v22 hypotheses into an existing queue."""
    queued = 0
    for win_name, timerange in WINDOWS.items():
        queue_hypothesis(
            config=SEED_CONFIG_V22,
            band="seed",
            rationale="seed [v22]: live-config baseline (5m, classifier, balanced)",
            window=win_name,
            timerange=timerange,
        )
        queued += 1
    return queued


def _stamp_target_version(config: dict) -> dict:
    """Inject target_version into a config dict (v23 zscore, v22 raw_pct).

    Allows promote.py to exclude the 268 legacy raw-% experiments (which lack
    this field) from promotion decisions. Called before every queue_hypothesis().
    """
    arch = config.get("arch", "v23")
    if "target_version" not in config:
        config = dict(config)
        config["target_version"] = TARGET_VERSION if arch == "v23" else "raw_pct"
    return config


def generate_and_queue(safe_n: int = 6, aggressive_n: int = 6, windows: list[str] | None = None) -> int:
    """
    One brain cycle: generate safe + aggressive variants for BOTH architectures,
    queue on each window. Returns count of newly queued hypotheses.

    Window order matters for speed-to-promotion: each variant is queued as
    (bull_2024Q1, bear_2025Q1, bull_2024Q4, bear_2026Q1) so that the runner always
    processes one bull → one bear back-to-back for every config. This means a
    promising config gets BOTH a bull and a bear result within ~3h instead of
    waiting for the entire bull backlog to drain first.

    REBALANCED 2026-06-19: now uses GENUINE bull windows (bull_2024Q1 +68%,
    bull_2024Q4 +47%). The old rotation's "bull" slots (bull_2024Q2, bull_2025Q4)
    were actually −11% and −23% down markets — renamed to bear_* and dropped here.
    bear_2026Q1 is the promotion gate (BEAR_2026Q1_REQUIRED). 2:2 balance keeps
    next_alternating() from exhausting the bear queue.
    """
    from experiment_log import read_queue as _rq
    # Paired window order: bull, bear, bull, bear — tested back-to-back per config.
    PAIRED_WINDOWS = [
        "bull_2024Q1",  # genuine bull (+68%, halving run-up)
        "bear_2025Q1",  # genuine bear (−12%, best PF/WR on bear historically)
        "bull_2024Q4",  # genuine bull (+47%, recent → 36/38 pair coverage)
        "bear_2026Q1",  # promotion gate window (must pass WR≥50%), live-condition bear
        # 2:2 balance ensures next_alternating() always finds a bear entry (2026-06-04 fix).
    ]
    target_windows = windows or PAIRED_WINDOWS
    safe = generate_safe_band_both(n_per_arch=safe_n // 2 + safe_n % 2)
    aggr = generate_aggressive_band(n=aggressive_n)
    all_variants = safe + aggr

    # Build set of (config_hash, window) already in queue to avoid re-queueing.
    from promote import _config_hash as _ch
    already_queued = {
        (_ch(r["config"]), r.get("window", ""))
        for r in _rq()
    }

    # B2 (2026-06-11): refuse param-only experiments on exhausted families.
    # A "family" is (window, model-shaping fields). Once a family has accumulated
    # EXHAUSTED_FAMILY_LIMIT unsuccessful runs, more threshold/geometry tweaks
    # inside it are statistically pointless — new experiments there require a
    # changed feature set / strategy / timeframe. (420+ absolute-threshold
    # experiments found nothing; this encodes that lesson.)
    fail_counts: dict[tuple, int] = {}
    for r in read_log():
        st = r.get("status")
        unsuccessful = st in ("scout_failed", "failed") or (
            st == "completed"
            and (r.get("metrics", {}).get("profit_pct") or 0) <= 0
        )
        if unsuccessful:
            key = _family_key(r.get("config", {}), r.get("window", ""))
            fail_counts[key] = fail_counts.get(key, 0) + 1
    exhausted_notified: set[tuple] = set()

    queued = 0
    for v in all_variants:
        cfg = _stamp_target_version(v["config"])
        for win_name in target_windows:
            if win_name not in WINDOWS:
                continue
            if (_ch(cfg), win_name) in already_queued:
                continue  # Fix 13: skip already-queued (config, window) pairs
            fam = _family_key(cfg, win_name)
            if fail_counts.get(fam, 0) >= EXHAUSTED_FAMILY_LIMIT:
                if fam not in exhausted_notified:
                    exhausted_notified.add(fam)
                    print(f"[brain] family EXHAUSTED ({fail_counts[fam]} failures) on "
                          f"{win_name}: tf={cfg.get('timeframe')} feat={cfg.get('feature_set')} "
                          f"— refusing more param-only configs")
                    _notify_family_exhausted(cfg, win_name, fail_counts[fam])
                continue
            queue_hypothesis(
                config=cfg,
                band=v["band"],
                rationale=v["rationale"],
                window=win_name,
                timerange=WINDOWS[win_name],
                parent_id=v.get("parent_id"),
            )
            queued += 1
    return queued


